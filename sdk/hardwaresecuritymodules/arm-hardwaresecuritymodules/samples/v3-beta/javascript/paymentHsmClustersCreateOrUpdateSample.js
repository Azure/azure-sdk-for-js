const { AzureDedicatedHSMResourceProvider } = require("@azure/arm-hardwaresecuritymodules");
const { DefaultAzureCredential } = require("@azure/identity");

/**
 * This sample demonstrates how to create or Update a Payment HSM Cluster in the specified subscription.
 *
 * @summary create or Update a Payment HSM Cluster in the specified subscription.
 * x-ms-original-file: 2025-12-01-preview/PaymentHsmCluster_CreateOrUpdate_MaximumSet_Gen.json
 */
async function paymentHsmClusterCreateOrUpdateMaximumSetGen() {
  const credential = new DefaultAzureCredential();
  const subscriptionId = "00000000-0000-0000-0000-000000000000";
  const client = new AzureDedicatedHSMResourceProvider(credential, subscriptionId);
  const result = await client.paymentHsmClusters.createOrUpdate("rgpaymenthsm", "phsm1", {
    location: "eastus2",
    properties: {
      autoGeneratedDomainNameLabelScope: "TenantReuse",
      publicNetworkAccess: "Disabled",
      applicationTrustedIssuer: "ApplicationBase64DerIssuerCertificate",
      managementTrustedIssuer: "ManagementBase64DerIssuerCertificate",
    },
    tags: { Dept: "paymenthsm", Environment: "dogfood" },
    sku: { name: "Payments_v2", family: "B" },
  });
  console.log(result);
}

async function main() {
  await paymentHsmClusterCreateOrUpdateMaximumSetGen();
}

main().catch(console.error);
